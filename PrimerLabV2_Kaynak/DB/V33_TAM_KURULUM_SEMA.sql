CREATE TABLE IF NOT EXISTS "SiparisKalemleri"
(
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SiparisId" integer NOT NULL,
    "IsTuru" text NOT NULL,
    "Adet" integer NOT NULL DEFAULT 1,

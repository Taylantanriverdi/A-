-- ---------------------------------------------------------------- Uygulama rolü yetkileri
-- primerlab_app rolü kurulum betiği tarafından oluşturulur. Rol süper kullanıcı
-- değildir; yalnız veri işlemleri yapabilir.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'primerlab_app') THEN
        GRANT USAGE ON SCHEMA public TO primerlab_app;
        GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO primerlab_app;
        GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO primerlab_app;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO primerlab_app;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO primerlab_app;
    END IF;
END $$;


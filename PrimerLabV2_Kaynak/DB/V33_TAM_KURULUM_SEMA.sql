-- (NULL) veya varsayılan değerlidir.

SET client_encoding = 'UTF8';
-- "zaten var, atlanıyor" bildirimleri gizlenir; gerçek uyarılar (WARNING) görünür.
SET client_min_messages = warning;

BEGIN;

-- ---------------------------------------------------------------- EF tabloları
CREATE TABLE IF NOT EXISTS "Hekimler"
(
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AdSoyad" text NOT NULL,
    "KlinikAdi" text NULL,
    "Telefon" text NULL,
    "Email" text NULL,
    "Aktif" boolean NOT NULL DEFAULT true,
    "OlusturmaTarihi" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "Teknisyenler"
(
    "Id" serial PRIMARY KEY,
    "AdSoyad" character varying(150) NOT NULL,
    "Aktif" boolean NOT NULL DEFAULT true,
    "OlusturmaTarihi" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "Hastalar"
(
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "AdSoyad" text NOT NULL,
    "HekimId" integer NOT NULL,
    "Telefon" text NULL,
    "Notlar" text NULL,
    "OlusturmaTarihi" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "Aktif" boolean NOT NULL DEFAULT true,
    CONSTRAINT "FK_Hastalar_Hekimler_HekimId" FOREIGN KEY ("HekimId")
        REFERENCES "Hekimler"("Id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "Siparisler"
(
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "HastaId" integer NOT NULL,
    "Durum" text NOT NULL,
    "Notlar" text NULL,
    "OlusturmaTarihi" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "TeslimTarihi" timestamp with time zone NULL,
    "Aktif" boolean NOT NULL DEFAULT true,
    CONSTRAINT "FK_Siparisler_Hastalar_HastaId" FOREIGN KEY ("HastaId")
        REFERENCES "Hastalar"("Id") ON DELETE RESTRICT
);

